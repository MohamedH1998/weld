// node checks/catalogue.mjs — draws every accepted diagram's contact sheet into catalogue/<slug>.png and writes CATALOGUE.md
// from src/canvas/catalogue.ts. (pnpm dev running on :3100.) Fails if a diagram has no entry, or an entry no diagram.
import { execSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { CATALOGUE } from "../src/canvas/catalogue.ts";
// (the engine's diagrams are in the package)
const PKG = "../../packages/canvas/src/";

const ORDER = ["flow", "phase", "cycle", "comparison", "decomposition", "containment", "hierarchy", "network"];
const HEAD = { flow: "Flow: something travels", phase: "Phase: one thing moves through states", cycle: "Cycle: it comes round again", comparison: "Comparison: two side by side", decomposition: "Decomposition: a whole taken apart", containment: "Containment: inside and outside", hierarchy: "Hierarchy: levels", network: "Network: many to many" };
// which accepted diagrams an agent can copy from source (the short form); the rest are pictures to learn from
const SHORT = Object.fromEntries([["built", readFileSync(`${PKG}built.ts`, "utf8")], ["notched", readFileSync(`${PKG}notched.ts`, "utf8")], ["picked", readFileSync(`${PKG}picked.ts`, "utf8")], ...["r21a3", "r25f", "r25g", "r26n", "r26p", "r27b", "r27d"].map((t) => [`trial/${t}`, readFileSync(`${PKG}trial/${t}.ts`, "utf8")])].flatMap(([f, s]) => [...s.matchAll(/slug: "([^"]+)"/g)].map((m) => [m[1], `packages/canvas/src/${f}.ts`])));

const out = execSync("node checks/look.mjs src/canvas/accepted.ts", { encoding: "utf8", timeout: 590000 });
const drawn = [...out.matchAll(/^([\w-]+): \d+ moments/gm)].map((m) => m[1]);
const have = new Set(CATALOGUE.map((e) => e.slug));
const bad = [...drawn.filter((s) => !have.has(s)).map((s) => `${s}: accepted but not in the catalogue`), ...[...have].filter((s) => !drawn.includes(s)).map((s) => `${s}: in the catalogue but not accepted`)];
if (bad.length) { console.error(bad.join("\n")); process.exit(1); }
mkdirSync("catalogue", { recursive: true });
for (const s of drawn) copyFileSync(`checks/shots/look-${s}.png`, `catalogue/${s}.png`);
const moments = Object.fromEntries([...out.matchAll(/^([\w-]+): (\d+) moments/gm)].map((m) => [m[1], +m[2]]));

const md = [
  "<!-- Generated by checks/catalogue.mjs from src/canvas/catalogue.ts. Edit that, then run it. -->",
  "# Catalogue",
  "",
  "Every accepted diagram, by the relationship it shows. Before you draw, write your own one sentence (\"the viewer sees [one change], which explains [one relationship]\"), then find the one or two entries below whose **shows** is nearest to it, whatever their subject. Open their sheets (every moment, in order) with your image reader, and take what **borrow** names. A familiar subject is not a match: a cache diagram may be nearest to a queue's picture.",
  "",
  "Do not start from the same picture every time. If your sentence is about time, proportion or a part of a whole, the nearest entry is not a row of boxes.",
  "",
  ...ORDER.flatMap((c) => {
    const es = CATALOGUE.filter((e) => e.composition[0] === c);
    if (!es.length) return [];
    return [`## ${HEAD[c]}`, "", ...es.flatMap((e) => [
      `### ${e.slug}`,
      "",
      `**Shows:** ${e.shows}  `,
      `**Picture:** ${e.picture} (${moments[e.slug]} moments)  `,
      `**Fits:** ${e.fits}  `,
      `**Not for:** ${e.not}  `,
      `**Borrow:** ${e.borrow}  `,
      `**Avoid:** ${e.avoid}  `,
      `**Sheet:** \`catalogue/${e.slug}.png\` · **Source:** ${SHORT[e.slug] ? `\`${SHORT[e.slug]}\` (short form: copy and change it)` : "picture only (drawn by hand; rebuild what you borrow with mk.ts)"}`,
      "",
    ])];
  }),
].join("\n");
writeFileSync("CATALOGUE.md", md);
console.log(`${CATALOGUE.length} entries, ${drawn.length} sheets -> CATALOGUE.md, catalogue/`);
