// The only door between the page and the app's own process.
const { contextBridge, ipcRenderer, webUtils } = require("electron");

const on = (channel) => (fn) => {
  const h = (_e, ...args) => fn(...args);
  ipcRenderer.on(channel, h);
  return () => ipcRenderer.removeListener(channel, h);
};

contextBridge.exposeInMainWorld("weld", {
  info: ipcRenderer.sendSync("app:infoSync"),
  agentsNow: () => ipcRenderer.sendSync("app:agentsSync"),
  agentList: () => ipcRenderer.sendSync("app:agentListSync"),
  assets: {
    put: (buf, meta) => ipcRenderer.invoke("asset:put", buf, meta),
    importFile: (abs) => ipcRenderer.invoke("asset:importFile", abs),
    read: (hash, ext, preview) => ipcRenderer.invoke("asset:read", hash, ext, preview),
    origins: (list) => ipcRenderer.invoke("asset:origins", list),
    snapshot: (wcId, name) => ipcRenderer.invoke("browser:snapshot", wcId, name),
    // a dropped file's place on disk (for a picture that came from one, so changes to it show)
    pathOf: (file) => { try { return webUtils.getPathForFile(file) || ""; } catch { return ""; } },
  },
  onImage: on("board:image"),
  onImageChanged: on("board:imageChanged"),
  saveAgent: (c) => ipcRenderer.invoke("agents:saveCommand", c),
  t3: { state: () => ipcRenderer.invoke("t3:state"), connect: () => ipcRenderer.invoke("t3:connect"), disconnect: () => ipcRenderer.invoke("t3:disconnect") },
  removeAgent: (id) => ipcRenderer.invoke("agents:removeCommand", id),
  board: {
    load: () => ipcRenderer.sendSync("board:loadSync"),
    save: (board) => ipcRenderer.invoke("board:save", board),
    saveNow: (board) => ipcRenderer.sendSync("board:saveSync", board),
    keepAside: (board) => ipcRenderer.sendSync("board:keepAside", board),
    threads: (ids, ok, board) => ipcRenderer.send("board:threads", ids, ok, board),
  },
  boards: {
    list: () => ipcRenderer.invoke("boards:list"),
    create: (name, dir) => ipcRenderer.invoke("boards:create", name, dir),
    open: (id) => ipcRenderer.invoke("boards:open", id),
    rename: (id, name) => ipcRenderer.invoke("boards:rename", id, name),
    setDir: (id, dir) => ipcRenderer.invoke("boards:setDir", id, dir),
    putAway: (id) => ipcRenderer.invoke("boards:putAway", id),
  },
  scratch: () => ipcRenderer.sendSync("scratch:newSync"),
  saveSettings: (s) => ipcRenderer.invoke("settings:save", s),
  pickFolder: (start) => ipcRenderer.invoke("dialog:folder", start),
  openExternal: (url) => ipcRenderer.invoke("shell:external", url),
  reveal: (p) => ipcRenderer.invoke("shell:reveal", p),
  servers: () => ipcRenderer.invoke("servers"),
  pty: {
    open: (id, opts) => ipcRenderer.invoke("pty:open", id, opts),
    write: (id, data) => ipcRenderer.send("pty:write", id, data),
    rerun: (id, command) => ipcRenderer.invoke("pty:rerun", id, command),
    typed: (id) => ipcRenderer.send("pty:typed", id),
    resize: (id, cols, rows) => ipcRenderer.send("pty:resize", id, cols, rows),
    close: (id) => ipcRenderer.invoke("pty:close", id),
    cwd: (id) => ipcRenderer.invoke("pty:cwd", id),
    onEvent: on("pty:event"),
  },
  thread: {
    get: (id) => ipcRenderer.invoke("thread:get", id),
    send: (id, msg) => ipcRenderer.invoke("thread:send", id, msg),
    stop: (id) => ipcRenderer.invoke("thread:stop", id),
    warm: (id) => ipcRenderer.send("thread:warm", id),
    set: (id, change) => ipcRenderer.invoke("thread:set", id, change),
    seen: (id) => ipcRenderer.invoke("thread:seen", id),
    unqueue: (id, at) => ipcRenderer.invoke("thread:unqueue", id, at),
    sendQueued: (id, at) => ipcRenderer.invoke("thread:sendQueued", id, at),
    answer: (id, askId, allow) => ipcRenderer.invoke("thread:answer", id, askId, allow),
    unservice: (id, svc) => ipcRenderer.invoke("thread:unservice", id, svc),
    fork: (from, to) => ipcRenderer.invoke("thread:fork", from, to),
    forget: (id) => ipcRenderer.invoke("thread:forget", id),
    onBoard: (ids) => ipcRenderer.invoke("thread:onBoard", ids),
    onEvent: on("thread:event"),
  },
  onMenu: on("menu"),
  onDo: on("board:do"),
  onLook: on("board:look"),
  onDraw: on("board:draw"),
  drew: (req, r) => ipcRenderer.send("board:drew", req, r),
  onGuide: on("board:guide"),
  guided: (req, text) => ipcRenderer.send("board:guided", req, text),
  looked: (req, refs) => ipcRenderer.send("board:looked", req, refs),
  onPages: on("board:pages"),
  pagesAre: (req, list) => ipcRenderer.send("board:pagesAre", req, list),
  onPoint: on("board:point"),
  onUsing: on("board:using"),
  onAcpNew: on("acp:newThread"),
  acpMade: (req) => ipcRenderer.send("acp:made", req),
  onOpen: on("browser:open"),
  onPinch: on("browser:pinch"),
  onStill: on("browser:still"),
  stillNow: (id) => ipcRenderer.send("browser:stillNow", id),
  pageAsleep: (id, on) => ipcRenderer.send("browser:asleep", id, on),
  localUrl: (u, given) => ipcRenderer.invoke("local:url", u, given === true),
  onReveal: on("app:reveal"),
  onFocus: on("app:focus"),
  onEnv: on("app:env"),
  envKnown: () => ipcRenderer.sendSync("app:envKnownSync"),
});
